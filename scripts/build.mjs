function tailwindCss() {
  const declarations = (entries) =>
    entries.map(([name, value]) => `  --${name}: ${value};`).join('\n');
  const colors = flatten(primitives.color).map(([name, value]) => [
    `color-oe-${name}`,
    value,
  ]);
  const radii = flatten(primitives.radius).map(([name, value]) => [
    `radius-brand-${name}`,
    value,
  ]);
  const semanticColors = Object.keys(semantic.light)
    .filter((key) => !key.startsWith('shadow-'))
    .map((key) => [`color-${key}`, `var(--oe-${key})`]);
  const semanticShadows = [
    ['shadow-brand-sm', 'var(--oe-shadow-sm)'],
    ['shadow-brand-md', 'var(--oe-shadow-md)'],
  ];

  return `/*
 * Generated Tailwind CSS v4 adapter. Import after "tailwindcss".
 */

@import "./tokens.css";

@custom-variant dark (&:where(.dark, .dark *));

@theme static {
${declarations(colors)}
  --font-brand-sans: ${primitives.font.sans};
  --font-brand-serif: ${primitives.font.serif};
  --font-brand-mono: ${primitives.font.mono};
${declarations(radii)}
}

@theme inline {
${declarations(semanticColors)}
${declarations(semanticShadows)}
}
`;
}

