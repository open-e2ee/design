/*
 * The Carrier mark.
 *
 * Two hollow carrier brackets hold one solid payload that touches neither of
 * them. Everything is a single fill color: no strokes, no radii, no gradients,
 * no second tone. The payload is square at every size; the two variants differ
 * so the silhouette survives at favicon sizes.
 */

const markSizes = [16, 24, 32, 48, 64, 128, 256, 512, 1024];

function variantForSize(size) {
  if (size < geometry.minimumSize) {
    throw new Error(`The mark is not reproduced below ${geometry.minimumSize} px.`);
  }
  return size <= geometry.smallMaximumSize ? 'optical' : 'full';
}

function markPaths(variant) {
  const { carrierLeftPath, carrierRightPath, payloadPath } = geometry[variant];
  return [carrierLeftPath, carrierRightPath, payloadPath];
}

const markDescription = {
  full:
    'Two open carrier brackets holding a solid square payload. The payload ' +
    'touches neither bracket.',
  optical:
    'Two open carrier brackets holding a solid square payload. Small-size ' +
    'optical variant, drawn with thicker stems for favicon scale.',
};

function markMarkup(fill, variant, indent = '  ') {
  return markPaths(variant)
    .map((path) => `${indent}<path d="${path}" fill="${fill}"/>`)
    .join('\n');
}

const forcedColors = `    @media (forced-colors: active) {
      path { fill: CanvasText; }
    }`;

function standaloneSvg({ mode, fill, variant, background }) {
  const sizeLabel = variant === 'optical' ? ' small-size' : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="${geometry.viewBox}" role="img" aria-labelledby="title desc">
  <title id="title">OpenE2EE${sizeLabel} mark — ${mode}</title>
  <desc id="desc">${markDescription[variant]}</desc>
  <metadata>Mark: carrier; variant: ${variant}; mode: ${mode}; intended background: ${background}; generated by @open-e2ee/design ${packageJson.version}.</metadata>
  <style>
${forcedColors}
  </style>
${markMarkup(fill, variant)}
</svg>
`;
}

function adaptiveSvg(variant, { title, width = 512 } = {}) {
  const sizeLabel = variant === 'optical' ? ' small-size' : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${width}" viewBox="${geometry.viewBox}" role="img" aria-labelledby="title desc">
  <title id="title">${title ?? `Adaptive OpenE2EE${sizeLabel} mark`}</title>
  <desc id="desc">${markDescription[variant]} The fill follows the active color scheme.</desc>
  <style>
    :root { --oe-mark: ${brand.modes.light.mark}; }
    @media (prefers-color-scheme: dark) {
      :root { --oe-mark: ${brand.modes.dark.mark}; }
    }
${forcedColors}
  </style>
${markMarkup('var(--oe-mark)', variant)}
</svg>
`;
}

